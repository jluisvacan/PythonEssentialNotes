"""
    El metodo center() centra la cadena en el espacio indicado.

    Ejemplo:
        "example".center(20)
        #centra la cadena dentro de un espacio de 20 caracteres
"""

print('[' + 'word'.center(10) + ']')



# La variante con dos parametros permite indicar el caracter con el que se centrara la cadena
print('[' + 'double'.center(20, '*') + ']')

