"""
    El metodo isalpha() valida que la cadena contine solo digitos alfabeticos.
    Devuelve un valor booleano.

    Ejemplo:
        "example".isalpha()

"""

chain = 'HelloWorld'
chain2 = 'Hello World'
number = '123'

print(chain.isalpha())      #True
print(chain2.isalpha())      #False
print(number.isalpha())     #False