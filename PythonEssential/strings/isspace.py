"""
    El metodo isspace() identifica si la cadena corresponde a espacios en blanco.
    Devuelve un valor booleano.

    Ejemplo:
        "example".isspace()

"""

chain = 'HelloWorld'
chain2 = 'hello world'
chain3 = ' '

print(chain.isspace())      #False
print(chain2.isspace())     #False
print(chain3.isspace())     #True